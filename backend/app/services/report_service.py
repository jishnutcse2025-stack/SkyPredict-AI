"""
SkyPredict AI - Professional Report Generation Service
Generates authentic PDF reports using ReportLab and CSV exports.
Follows SkyPredict AI aviation design system (Navy, Royal Blue, Lavender).
"""

import io
import csv
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
    KeepTogether
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch

# Color Palette
NAVY = colors.HexColor("#10264A")
ROYAL_BLUE = colors.HexColor("#2878D4")
SKY_BLUE = colors.HexColor("#69B7FF")
LAVENDER = colors.HexColor("#8B7CF6")
BG_PALE = colors.HexColor("#EAF2FF")
SURFACE_PALE = colors.HexColor("#F0EDFF")
DARK_TEXT = colors.HexColor("#17365D")
MUTED_TEXT = colors.HexColor("#5A6E85")
AMBER = colors.HexColor("#F5A34D")
TEAL = colors.HexColor("#24B8A6")

def generate_pdf_report(
    report_type: str = "overall",
    title: str = "SkyPredict AI Flight Analytics & Operations Report",
    data_summary: dict = None,
    prediction_record: dict = None,
    model_metrics: dict = None,
    route_details: dict = None,
    disclaimer: bool = True
) -> bytes:
    """
    Builds a professional, multi-section PDF document matching SkyPredict AI branding.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()

    # Custom typography styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=NAVY
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=MUTED_TEXT
    )
    h2_style = ParagraphStyle(
        "SectionHeader",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=16,
        textColor=ROYAL_BLUE,
        spaceBefore=14,
        spaceAfter=6
    )
    body_style = ParagraphStyle(
        "Body",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=DARK_TEXT
    )
    disclaimer_style = ParagraphStyle(
        "Disclaimer",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8,
        leading=11,
        textColor=MUTED_TEXT
    )
    th_style = ParagraphStyle(
        "TableHeader",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8.5,
        leading=11,
        textColor=colors.white
    )
    td_style = ParagraphStyle(
        "TableCell",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=11,
        textColor=DARK_TEXT
    )

    story = []

    # 1. Header & Branding Banner
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
    header_data = [
        [
            Paragraph("<b>SkyPredict AI</b>", title_style),
            Paragraph(f"<b>Generated:</b> {now_str}<br/><b>System:</b> Aviation Analytics v2.4", subtitle_style)
        ],
        [
            Paragraph("Smarter Predictions. Smoother Journeys.", subtitle_style),
            Paragraph(f"<b>Report Category:</b> {report_type.replace('_', ' ').title()}", subtitle_style)
        ]
    ]
    header_table = Table(header_data, colWidths=[3.8 * inch, 3.7 * inch])
    header_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('ALIGN', (1, 0), (1, -1), 'RIGHT'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 2),
    ]))
    story.append(header_table)
    story.append(Spacer(1, 8))
    story.append(HRFlowable(width="100%", thickness=2, color=ROYAL_BLUE, spaceBefore=4, spaceAfter=12))

    # 2. Executive Summary
    story.append(Paragraph("Executive Summary & Operational Overview", h2_style))
    summary_text = (
        "This official intelligence report is generated by SkyPredict AI's predictive analytics engine. "
        "Calculations are synthesized from verified historical flight operations records and multi-algorithm "
        "machine learning pipelines to support proactive scheduling, disruption mitigation, and fleet punctuality management."
    )
    story.append(Paragraph(summary_text, body_style))
    story.append(Spacer(1, 10))

    # 3. Overall Benchmark Statistics Table
    if data_summary and "stats" in data_summary:
        st = data_summary["stats"]
        story.append(Paragraph("Dataset Corpus & Performance Benchmarks", h2_style))
        stats_rows = [
            [
                Paragraph("<b>Total Flights Analyzed</b>", td_style),
                Paragraph(f"{st.get('total_flights_analyzed', 0):,}", td_style),
                Paragraph("<b>Delayed Flights (>=15m)</b>", td_style),
                Paragraph(f"{st.get('delayed_flights', 0):,}", td_style),
            ],
            [
                Paragraph("<b>On-Time Flights</b>", td_style),
                Paragraph(f"{st.get('on_time_flights', 0):,}", td_style),
                Paragraph("<b>Industry Delay Rate</b>", td_style),
                Paragraph(f"{st.get('delay_rate_pct', 0.0)}%", td_style),
            ],
            [
                Paragraph("<b>Average Delay Duration</b>", td_style),
                Paragraph(f"{st.get('average_delay_minutes', 0.0)} mins", td_style),
                Paragraph("<b>Data Classification</b>", td_style),
                Paragraph(st.get("dataset_type", "Historical Benchmark"), td_style),
            ]
        ]
        stat_table = Table(stats_rows, colWidths=[2.0 * inch, 1.7 * inch, 2.0 * inch, 1.8 * inch])
        stat_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), BG_PALE),
            ('BOX', (0, 0), (-1, -1), 0.5, ROYAL_BLUE),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#D2E3FC")),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(stat_table)
        story.append(Spacer(1, 12))

    # 4. Prediction Assessment (if prediction_record provided)
    if prediction_record:
        story.append(Paragraph("Flight Prediction Assessment Detail", h2_style))
        is_del = prediction_record.get("is_delayed", False)
        status_color = "#E53E3E" if is_del else "#24B8A6"
        pred_rows = [
            [
                Paragraph("<b>Flight Number</b>", td_style),
                Paragraph(str(prediction_record.get("flight_number")), td_style),
                Paragraph("<b>Carrier</b>", td_style),
                Paragraph(f"{prediction_record.get('airline')} ({prediction_record.get('airline_name', '')})", td_style),
            ],
            [
                Paragraph("<b>Route</b>", td_style),
                Paragraph(f"{prediction_record.get('origin')} → {prediction_record.get('dest')}", td_style),
                Paragraph("<b>Departure Schedule</b>", td_style),
                Paragraph(f"{prediction_record.get('flight_date')} @ {prediction_record.get('sched_dep_hour', 0):02d}:00", td_style),
            ],
            [
                Paragraph("<b>Prediction Outcome</b>", td_style),
                Paragraph(f"<font color='{status_color}'><b>{prediction_record.get('prediction_label')}</b></font>", td_style),
                Paragraph("<b>Delay Probability</b>", td_style),
                Paragraph(f"{prediction_record.get('delay_probability', 0.0) * 100:.1f}%", td_style),
            ],
            [
                Paragraph("<b>Estimated Delay</b>", td_style),
                Paragraph(f"{prediction_record.get('estimated_delay_minutes', 0.0)} mins", td_style),
                Paragraph("<b>Model Evaluator</b>", td_style),
                Paragraph(str(prediction_record.get("model_used")), td_style),
            ],
        ]
        pred_table = Table(pred_rows, colWidths=[2.0 * inch, 1.7 * inch, 2.0 * inch, 1.8 * inch])
        pred_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), SURFACE_PALE),
            ('BOX', (0, 0), (-1, -1), 0.5, LAVENDER),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#D8B4FE")),
            ('TOPPADDING', (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ]))
        story.append(pred_table)
        story.append(Spacer(1, 10))

        # Explainability contributions
        contributions = prediction_record.get("contributions", [])
        if contributions:
            story.append(Paragraph("Explainability & Key Contributing Drivers", h2_style))
            contrib_rows = [[
                Paragraph("<b>Operational Feature</b>", th_style),
                Paragraph("<b>Observed Value</b>", th_style),
                Paragraph("<b>Influence Direction</b>", th_style),
                Paragraph("<b>Relative Impact</b>", th_style),
            ]]
            for c in contributions[:5]:
                direction_txt = "Increases Delay Propensity" if c.get("direction") == "increases_delay_risk" else "Promotes On-Time Reliability"
                contrib_rows.append([
                    Paragraph(c.get("display_name", c.get("feature")), td_style),
                    Paragraph(str(c.get("input_value", "N/A")), td_style),
                    Paragraph(direction_txt, td_style),
                    Paragraph(f"{c.get('importance_pct', 0.0)}%", td_style),
                ])
            contrib_table = Table(contrib_rows, colWidths=[2.3 * inch, 1.5 * inch, 2.4 * inch, 1.3 * inch])
            contrib_table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), NAVY),
                ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ('TOPPADDING', (0, 0), (-1, -1), 4),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ]))
            story.append(contrib_table)
            story.append(Spacer(1, 10))

    # 5. Model Evaluation Metrics
    if model_metrics and "classification_models" in model_metrics:
        story.append(Paragraph("Machine Learning Algorithm Comparison", h2_style))
        mod_rows = [[
            Paragraph("<b>Algorithm</b>", th_style),
            Paragraph("<b>Model Class</b>", th_style),
            Paragraph("<b>Accuracy</b>", th_style),
            Paragraph("<b>Precision</b>", th_style),
            Paragraph("<b>Recall</b>", th_style),
            Paragraph("<b>F1 Score</b>", th_style),
            Paragraph("<b>ROC-AUC</b>", th_style),
        ]]
        for m_key, m_info in model_metrics["classification_models"].items():
            met = m_info.get("metrics", {})
            mod_rows.append([
                Paragraph(m_info.get("display_name", m_key), td_style),
                Paragraph(m_info.get("model_type", "Standard"), td_style),
                Paragraph(f"{met.get('accuracy', 0.0):.4f}", td_style),
                Paragraph(f"{met.get('precision', 0.0):.4f}", td_style),
                Paragraph(f"{met.get('recall', 0.0):.4f}", td_style),
                Paragraph(f"{met.get('f1_score', 0.0):.4f}", td_style),
                Paragraph(f"{met.get('roc_auc', 0.0):.4f}" if met.get("roc_auc") else "N/A", td_style),
            ])
        mod_table = Table(mod_rows, colWidths=[1.8 * inch, 1.6 * inch, 0.8 * inch, 0.8 * inch, 0.8 * inch, 0.8 * inch, 0.9 * inch])
        mod_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), ROYAL_BLUE),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(mod_table)
        story.append(Spacer(1, 12))

    # 6. Route Analytics Insights
    if route_details and "insights" in route_details:
        story.append(Paragraph("Empirical Route Intelligence & Delay Insights", h2_style))
        for ins in route_details["insights"]:
            story.append(Paragraph(f"• {ins}", body_style))
            story.append(Spacer(1, 3))
        story.append(Spacer(1, 10))

    # 7. Regulatory & Methodology Disclaimer
    if disclaimer:
        story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#CBD5E1"), spaceBefore=8, spaceAfter=8))
        story.append(Paragraph("<b>Methodology & Limitations Disclaimer:</b>", disclaimer_style))
        disc_text = (
            "SkyPredict AI models are trained on historical aviation operations data calibrated against standard "
            "US Department of Transportation definitions (departure delay >= 15 minutes). Model probability outputs "
            "represent empirical associations and likelihood indicators rather than guaranteed deterministic outcomes. "
            "Actual flight punctuality is subject to dynamic en-route weather, tactical air traffic control metering, "
            "security ground holds, and mechanical contingencies. Historical associations must not be interpreted as proven "
            "causation. For critical operational dispatch, adhere strictly to authorized FAA/airline dispatch clearances."
        )
        story.append(Paragraph(disc_text, disclaimer_style))

    doc.build(story)
    return buffer.getvalue()

def generate_csv_report(data_type: str = "history", records: list = None) -> str:
    """
    Generates CSV formatted string for tabular export.
    """
    output = io.StringIO()
    writer = csv.writer(output)

    if data_type == "history" and records:
        writer.writerow([
            "Prediction_ID", "Flight_Number", "Airline", "Origin", "Destination",
            "Flight_Date", "Departure_Hour", "Prediction_Label", "Is_Delayed",
            "Delay_Probability", "Estimated_Delay_Min", "Risk_Level", "Model_Used", "Timestamp"
        ])
        for r in records:
            writer.writerow([
                r.get("id"), r.get("flight_number"), r.get("airline"), r.get("origin"), r.get("dest"),
                r.get("flight_date"), r.get("sched_dep_hour"), r.get("prediction_label"),
                r.get("is_delayed"), r.get("delay_probability"), r.get("estimated_delay_minutes"),
                r.get("risk_level"), r.get("model_used"), r.get("created_at")
            ])
    elif data_type == "routes" and records:
        writer.writerow([
            "Origin", "Destination", "Route", "Total_Flights", "Delayed_Flights",
            "Delay_Rate_Pct", "Avg_Delay_Min", "Distance_Miles"
        ])
        for r in records:
            writer.writerow([
                r.get("origin"), r.get("dest"), r.get("route"), r.get("total_flights"),
                r.get("delayed_flights"), r.get("delay_rate_pct"), r.get("avg_delay_min"),
                r.get("distance_miles")
            ])
    else:
        writer.writerow(["Notice", "No records matched export criteria"])

    return output.getvalue()
